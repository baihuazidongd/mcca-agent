import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import http from 'node:http';
import net from 'node:net';
import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const root = process.env.MCCA_SMOKE_ROOT || path.resolve(import.meta.dirname, '..');
const { chromium } = require(require.resolve('playwright-core', { paths: [path.join(root, 'packages/runtime-core')] }));
const { createBrowserService } = require(path.join(root, 'packages/runtime-core/browser.cjs'));
const { createPaths } = require(path.join(root, 'packages/runtime-core/paths.cjs'));
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'mcca-ui-smoke-'));
const paths = createPaths({ MCCA_HOME: root, MCCA_DATA_DIR: dir });
async function freePort() { const s = net.createServer(); await new Promise(r => s.listen(0,'127.0.0.1',r)); const p = s.address().port; await new Promise(r=>s.close(r)); return p; }
const port = await freePort(), debugPort = await freePort();
const executablePath = process.env.MCCA_BROWSER || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe';
fs.writeFileSync(path.join(dir,'instances.json'), '{"installed":[],"resident":[]}');
let logs = '', browser, userContext;
const nodeExecutable = process.env.MCCA_SMOKE_ROOT ? path.join(root, 'runtime/node.exe') : process.execPath;
const portal = spawn(nodeExecutable, ['packages/portal/server.cjs'], { cwd: root, windowsHide: true, env: { ...process.env, MCCA_HOME:root, PORTAL_PORT:String(port), MCCA_DATA_DIR:dir, MCCA_SKILLS_DIR:path.join(dir,'skills'), MCCA_PLUGINS_DIR:path.join(dir,'plugins'), MCCA_INSTANCES_CONFIG:path.join(dir,'instances.json'), MCCA_PORTAL_PASSIVE:'1', MCCA_HERMES_AUTO_INSTALL:'0', ...(process.env.MCCA_SMOKE_ROOT ? { PATH: `${process.env.SystemRoot}/System32;${process.env.SystemRoot}/System32/WindowsPowerShell/v1.0` } : {}) }, stdio:['ignore','pipe','pipe'] });
portal.stdout.on('data', b=> { logs += b; }); portal.stderr.on('data', b=> { logs += b; });
const fixture = http.createServer((req,res) => { res.setHeader('content-type','text/html'); res.end('<!doctype html><title>Fixture</title><label>Name <input aria-label="Name"></label><button onclick="document.querySelector(\'output\').textContent=\'Done\'">Send</button><output></output>'); });
const service = createBrowserService({ paths });
try {
  await new Promise(r=> fixture.listen(0,'127.0.0.1',r));
  const base = `http://127.0.0.1:${port}`, fixtureURL = `http://127.0.0.1:${fixture.address().port}`;
  let ready = false;
  for (let i=0;i<80;i++) { try { if ((await fetch(base+'/api/status')).ok) {ready=true;break;} } catch {} await new Promise(r=>setTimeout(r,250)); }
  assert.ok(ready, logs);
  browser = await chromium.launch({ executablePath, headless:true });
  const page = await browser.newPage(); const errors=[]; page.on('pageerror', e=>errors.push(e.message));
  await page.goto(base+'/'); await page.getByRole('tab',{name:'工作台',exact:true}).click();
  const workbench = page.frameLocator('iframe[title="工作台"]');
  await workbench.getByRole('heading',{name:'工作台',exact:true}).waitFor();
  await workbench.getByRole('button',{name:'助理接入',exact:true}).click();
  await workbench.getByRole('button',{name:'生成接入配置'}).click();
  await workbench.locator('#result').filter({hasText:'mcca-workbench'}).waitFor();
  await workbench.getByRole('button',{name:'设备工具',exact:true}).click();
  await workbench.getByRole('button',{name:'刷新组件',exact:true}).click();
  await workbench.locator('#components-list').filter({hasText:'APK 反编译'}).waitFor();
  await workbench.getByRole('button',{name:'扩展与定制',exact:true}).click();
  await workbench.locator('#extension-kind').selectOption('skill');
  await workbench.locator('#extension-file').fill('smoke-skill/SKILL.md');
  await workbench.getByRole('button',{name:'读取路径 / 准备新文件',exact:true}).click();
  await workbench.locator('#extension-save:not([disabled])').waitFor();
  await workbench.locator('#extension-text').fill('# Smoke skill\nA temporary fixture.');
  await workbench.getByRole('button',{name:'验证并保存',exact:true}).click();
  await workbench.locator('#message').filter({hasText:'操作完成'}).waitFor();
  await workbench.getByRole('button',{name:'文件修订记录',exact:true}).click();
  await workbench.getByRole('button',{name:'回滚此修改',exact:true}).click();
  await workbench.locator('#result').filter({hasText:'revision'}).waitFor();
  const customPort = await freePort();
  const registered = await fetch(base+'/api/workbench/register',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({id:'smoke-ide',label:'Smoke IDE',page:'smoke-ide',group:'ide',port:customPort,command:process.execPath,args:[],capabilities:[]})});
  assert.equal(registered.status,200,await registered.text());
  await page.reload(); await page.getByRole('tab',{name:'Smoke IDE',exact:true}).waitFor();
  await page.goto(base+'/workbench.html'); fs.mkdirSync(path.join(root,'.playwright-mcp'),{recursive:true}); await page.screenshot({path:path.join(root,'.playwright-mcp/workbench.png'),fullPage:true});
  assert.deepEqual(errors,[]);
  const ai = await service.call({action:'open',profile:'smoke'}); const p=ai.pages[0].id;
  await service.call({action:'network',session:ai.id,capture:true});
  await service.call({action:'navigate',session:ai.id,page:p,url:fixtureURL});
  const snapshot = await service.call({action:'snapshot',session:ai.id,page:p}); assert.match(snapshot.tree,/Name/);
  await service.call({action:'fill',session:ai.id,page:p,role:'textbox',name:'Name',text:'mcca'});
  await service.call({action:'click',session:ai.id,page:p,role:'button',name:'Send'});
  assert.equal(await service.call({action:'eval',session:ai.id,page:p,expression:'document.querySelector("output").textContent'}),'Done');
  const network = await service.call({action:'network',session:ai.id});
  const flow = network.flows.find(f=>f.url.startsWith(fixtureURL)); assert.ok(flow);
  const detail = await service.call({action:'network_detail',session:ai.id,request:flow.id}); assert.match(Buffer.from(detail.responseBody,'base64').toString(),/Fixture/);
  const har = await service.call({action:'export_har',session:ai.id});
  assert.equal(har.responseBodiesIncluded,true);assert.ok(JSON.parse(fs.readFileSync(har.file,'utf8')).log.entries.some(e=>e.response.content.text));
  await assert.rejects(service.call({action:'click',session:ai.id,page:'other-task',role:'button',name:'Send'}),/page/);
  await service.call({action:'close',session:ai.id});
  userContext = await chromium.launchPersistentContext(path.join(dir,'personal-profile'),{executablePath,headless:true,args:[`--remote-debugging-port=${debugPort}`]});
  const personalPage=await userContext.newPage(); await personalPage.goto(fixtureURL);
  const personal = await service.call({action:'open',mode:'personal',endpoint:`http://127.0.0.1:${debugPort}`});
  assert.ok(personal.pages.some(p=>p.url.startsWith(fixtureURL)));
  await service.call({action:'close',session:personal.id});
  assert.equal(await personalPage.title(),'Fixture');
  console.log('PASS: portal UI, dynamic IDE tab, MCP configuration, AI browser interaction, session isolation, personal browser disconnect.');
} finally {
  await service.dispose(); await userContext?.close(); await browser?.close();
  await new Promise(r=>fixture.close(r)); if (portal.exitCode === null) { const exited = new Promise(r=>portal.once('exit',r)); portal.kill(); await exited; }
  fs.rmSync(dir,{recursive:true,force:true});
}
